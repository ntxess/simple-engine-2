"""Writes the scripted .seinput files of the reference scenarios.

usage: make_inputs.py OUT_DIR

Each script is a list of (ticks, held actions) segments starting at tick 1.
The output is sparse: a line at tick 1, at every change of the held set (with
its press and release edges) and at the last tick, so the file also fixes the
run length. A tick without a line repeats the previous held state with no
edges (core/util/LegacyInput.hpp).
"""

import pathlib
import sys

ACTIONS = ["Up", "Left", "Down", "Right", "Jump", "Exit", "Enter", "Back",
           "A1", "A2", "A3", "A4", "A5", "A6"]
RATE = 120


def mask(names):
    value = 0
    for name in names:
        value |= 1 << ACTIONS.index(name)
    return value


# The player moves 1 px per tick per held direction (Movement, core/command).
SCRIPTS = {
    # Lawnmower sweep through the generated stress enemies, from (200, 200).
    "stress": [
        (1400, ["Right"]), (250, ["Down"]), (1400, ["Left"]),
        (250, ["Down"]), (300, ["Right"]),
    ],
    # From (300, 540) along the row of test entities and back one lane lower.
    "effects": [
        (60, []), (1500, ["Right"]), (200, ["Down"]), (40, ["A1"]),
        (1500, ["Left"]), (200, ["Up"]), (100, []),
    ],
    # Diagonals, pauses and reversals among the denser patrol paths.
    "patrol": [
        (600, ["Down", "Right"]), (400, ["Up", "Right"]), (300, []),
        (900, ["Left"]), (400, ["Down"]), (500, ["Up", "Left"]),
        (20, ["Jump"]), (480, ["Right"]),
    ],
}


def write(path, segments):
    lines = [
        f"# seinput v1 rate={RATE}",
        "# actions (bit 0 first): " + " ".join(ACTIONS),
        "# tick held pressed released (hex); generated by "
        "tests/legacy/make_inputs.py",
    ]
    tick = 1
    held = 0
    for length, names in segments:
        new = mask(names)
        pressed = new & ~held
        released = held & ~new
        if tick == 1 or new != held:
            lines.append(f"{tick:x} {new:x} {pressed:x} {released:x}")
        held = new
        tick += length
    last = tick - 1
    if not lines[-1].startswith(f"{last:x} "):
        lines.append(f"{last:x} {held:x} 0 0")
    path.write_text("\n".join(lines) + "\n", encoding="ascii", newline="\n")
    return last


def main():
    out = pathlib.Path(sys.argv[1])
    for name, segments in SCRIPTS.items():
        ticks = write(out / f"{name}.seinput", segments)
        print(f"{name}: {ticks} ticks")


if __name__ == "__main__":
    main()
