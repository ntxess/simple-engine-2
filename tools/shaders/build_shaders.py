"""Compiles the renderer's HLSL shaders into C++ headers of byte arrays.

The shaders are engine/se_render/shaders/<name>.<stage>.hlsl, stage vert or
frag (docs/milestone-specs.md M7, "Shaders"; ADR-059).

  build_shaders.py spirv [--check [--expect-stale]] [--generated-dir DIR]
                         [--wsl-distro NAME]
      SPIR-V through glslang: glslangValidator -D -V -S <stage> -e main
      --auto-sampled-textures (HLSL input, Vulkan SPIR-V, the entry point
      main; separate textures and samplers become the combined image
      samplers SDL_GPU binds). Writes <name>.<stage>.spv.h into
      engine/se_render/shaders/generated/ (committed). On Windows glslang
      runs in WSL through wsl.exe (the Windows SDK's dxc has no SPIR-V
      code generator); on Linux it runs directly. --check regenerates into
      a temporary directory and fails on any difference with DIR (default
      the committed headers), on a missing header and on a header without
      a shader: the freshness test of the WSL presets.
  build_shaders.py dxil --dxc PATH --source FILE --out FILE
      DXIL through the Windows SDK's dxc.exe (shader model 6.0, the entry
      point main), at build time; the header goes into the build tree.

Every header defines one array, se::shaders::k<Name><Stage><Spirv|Dxil>,
for example kSpriteVertSpirv. glslang's output does not depend on the
source path and is deterministic, so a regenerated header is byte-identical
to the committed one. Python 3, stdlib only.
"""

import argparse
import difflib
import os
import pathlib
import platform
import shutil
import subprocess
import sys
import tempfile

REPO = pathlib.Path(__file__).resolve().parents[2]
SHADER_DIR = REPO / "engine" / "se_render" / "shaders"
GENERATED_DIR = SHADER_DIR / "generated"
STAGES = {"vert": "vs_6_0", "frag": "ps_6_0"}
GLSLANG_ARGS = ["-D", "-V", "-e", "main", "--auto-sampled-textures"]
COPYRIGHT = "// Copyright 2026 The simple-engine-2 Authors."
BYTES_PER_LINE = 12


def shader_sources():
    """(path, name, stage) of every shader, sorted by file name."""
    found = []
    for path in sorted(SHADER_DIR.glob("*.hlsl")):
        parts = path.name.split(".")
        if len(parts) != 3 or parts[1] not in STAGES:
            raise SystemExit(f"build_shaders: {path.name} is not "
                             f"<name>.<vert|frag>.hlsl")
        found.append((path, parts[0], parts[1]))
    return found


def camel(text):
    return "".join(part[:1].upper() + part[1:]
                   for part in text.replace("-", "_").split("_"))


def array_name(name, stage, kind):
    return f"k{camel(name)}{camel(stage)}{kind}"


def header_text(name, stage, kind, blob, guard, command):
    """A lint-clean header holding |blob| as a constexpr byte array."""
    lines = [
        COPYRIGHT,
        "//",
        "// Generated by tools/shaders/build_shaders.py from",
        f"// engine/se_render/shaders/{name}.{stage}.hlsl with",
        f"//   {command}",
        "// Do not edit; regenerate instead.",
        "",
        f"#ifndef {guard}",
        f"#define {guard}",
        "",
        "#include <cstdint>",
        "",
        "namespace se::shaders {",
        "",
        "// clang-format off",
        f"inline constexpr std::uint8_t {array_name(name, stage, kind)}[] = {{",
    ]
    for start in range(0, len(blob), BYTES_PER_LINE):
        chunk = blob[start:start + BYTES_PER_LINE]
        lines.append("    " + " ".join(f"0x{byte:02x}," for byte in chunk))
    lines += [
        "};",
        "// clang-format on",
        "",
        "}  // namespace se::shaders",
        "",
        f"#endif  // {guard}",
        "",
    ]
    return "\n".join(lines)


def spirv_guard(name, stage):
    return f"ENGINE_SE_RENDER_SHADERS_GENERATED_{name.upper()}_" \
           f"{stage.upper()}_SPV_H_"


def to_wsl_path(path):
    full = os.path.abspath(str(path))
    drive, rest = os.path.splitdrive(full)
    return "/mnt/" + drive[0].lower() + rest.replace("\\", "/")


def run_glslang(source, stage, output, distro):
    args = GLSLANG_ARGS[:2] + ["-S", stage] + GLSLANG_ARGS[2:]
    if platform.system() == "Windows":
        command = ["wsl.exe", "-d", distro, "--", "glslangValidator", *args,
                   "-o", to_wsl_path(output), to_wsl_path(source)]
    else:
        tool = shutil.which("glslangValidator")
        if tool is None:
            raise SystemExit("build_shaders: glslangValidator not found "
                             "(sudo apt install glslang-tools)")
        command = [tool, *args, "-o", str(output), str(source)]
    result = subprocess.run(command, capture_output=True, text=True,
                            errors="replace", check=False)
    if result.returncode != 0 or not pathlib.Path(output).exists():
        raise SystemExit(f"build_shaders: glslang failed on {source.name}:\n"
                         f"{result.stdout}{result.stderr}")


def glslang_command(stage):
    args = GLSLANG_ARGS[:2] + ["-S", stage] + GLSLANG_ARGS[2:]
    return "glslangValidator " + " ".join(args)


def generate_spirv(out_dir, distro):
    """Writes every SPIR-V header into |out_dir|; returns their names."""
    names = []
    with tempfile.TemporaryDirectory() as scratch:
        for source, name, stage in shader_sources():
            spv = pathlib.Path(scratch) / f"{name}.{stage}.spv"
            run_glslang(source, stage, spv, distro)
            blob = spv.read_bytes()
            header = f"{name}.{stage}.spv.h"
            text = header_text(name, stage, "Spirv", blob,
                               spirv_guard(name, stage),
                               glslang_command(stage))
            (pathlib.Path(out_dir) / header).write_text(text, newline="\n")
            names.append(header)
    return names


def compare_dirs(expected_dir, actual_dir, names):
    """Differences between the regenerated headers and |actual_dir|."""
    problems = []
    actual_dir = pathlib.Path(actual_dir)
    present = {path.name for path in actual_dir.glob("*.spv.h")}
    for name in names:
        fresh = (pathlib.Path(expected_dir) / name).read_text()
        target = actual_dir / name
        if not target.exists():
            problems.append(f"missing: {target} (run build_shaders.py spirv)")
            continue
        committed = target.read_text()
        if committed != fresh:
            diff = difflib.unified_diff(
                committed.splitlines(), fresh.splitlines(),
                f"{target} (committed)", f"{name} (regenerated)", lineterm="",
                n=1)
            shown = list(diff)[:20]
            problems.append(f"stale: {target}\n" + "\n".join(shown))
    for name in sorted(present - set(names)):
        problems.append(f"no shader for {actual_dir / name}")
    return problems


def cmd_spirv(args):
    target = pathlib.Path(args.generated_dir or GENERATED_DIR)
    if not args.check:
        target.mkdir(parents=True, exist_ok=True)
        names = generate_spirv(target, args.wsl_distro)
        print(f"build_shaders: wrote {len(names)} SPIR-V header(s) to "
              f"{target}")
        return 0
    with tempfile.TemporaryDirectory() as fresh:
        names = generate_spirv(fresh, args.wsl_distro)
        problems = compare_dirs(fresh, target, names)
    for problem in problems:
        print(problem)
    if args.expect_stale:
        if any(problem.startswith("stale:") for problem in problems):
            print("build_shaders: the planted stale header was reported "
                  "(expected)")
            return 0
        print("FAIL: no stale header reported in the planted directory")
        return 1
    if problems:
        print(f"FAIL: {len(problems)} SPIR-V header(s) differ from glslang's "
              f"output; run python tools/shaders/build_shaders.py spirv and "
              f"commit the result")
        return 1
    print(f"build_shaders: {len(names)} SPIR-V header(s) are fresh")
    return 0


def cmd_dxil(args):
    source = pathlib.Path(args.source)
    parts = source.name.split(".")
    if len(parts) != 3 or parts[1] not in STAGES:
        raise SystemExit(f"build_shaders: {source.name} is not "
                         f"<name>.<vert|frag>.hlsl")
    name, stage = parts[0], parts[1]
    out = pathlib.Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    dxil = out.with_name(out.name[:-2])
    command = [args.dxc, "-nologo", "-T", STAGES[stage], "-E", "main",
               "-Wno-ignored-attributes", "-Fo", str(dxil), str(source)]
    result = subprocess.run(command, capture_output=True, text=True,
                            errors="replace", check=False)
    if result.returncode != 0 or not dxil.exists():
        print(result.stdout + result.stderr)
        print(f"build_shaders: dxc failed on {source}")
        return 1
    guard = f"SE_RENDER_SHADERS_{name.upper()}_{stage.upper()}_DXIL_H_"
    text = header_text(name, stage, "Dxil", dxil.read_bytes(), guard,
                       f"dxc -T {STAGES[stage]} -E main")
    if not out.exists() or out.read_text() != text:
        out.write_text(text, newline="\n")
    return 0


def main():
    parser = argparse.ArgumentParser()
    sub = parser.add_subparsers(dest="command", required=True)
    spirv = sub.add_parser("spirv")
    spirv.add_argument("--check", action="store_true")
    spirv.add_argument("--expect-stale", action="store_true")
    spirv.add_argument("--generated-dir")
    spirv.add_argument("--wsl-distro", default="Ubuntu")
    dxil = sub.add_parser("dxil")
    dxil.add_argument("--dxc", required=True)
    dxil.add_argument("--source", required=True)
    dxil.add_argument("--out", required=True)
    args = parser.parse_args()
    if args.command == "spirv":
        return cmd_spirv(args)
    return cmd_dxil(args)


if __name__ == "__main__":
    sys.exit(main())
